"""Go clients that oapi-codegen generates from an OpenAPI spec.

oapi-codegen turns an OpenAPI 3 document into Go code; with ``client``
among the kinds it generates, each operation gets a request builder
``New<Operation>Request`` (``New<Operation>RequestWithBody`` when the
operation takes a body) that builds the request for the operation's method
and path under the server URL the client is given at run time. Read here,
for each ``//go:generate`` directive of a Go file that runs oapi-codegen:

- the program: ``oapi-codegen``, ``go tool oapi-codegen`` or ``go run`` of
  ``github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen`` or
  ``github.com/deepmap/oapi-codegen[/v2]/cmd/oapi-codegen`` (any version);
  a bare name is that generator only when the go.mod it runs under (the
  nearest one above the directive's file, or ``-modfile``) requires one of
  those modules and no fork of it;
- its flags (``-config``, ``-generate``, ``-o``) and the configuration file
  (``generate``, ``output``, ``output-options.name-normalizer``), with the
  paths relative to the directive's directory, where ``go generate`` runs
  it; without ``-generate`` or a config ``generate``, the generator's default
  kinds, which include ``client``;
- the spec, its first argument, a JSON or YAML file in the repository.

Each operation of the spec's ``paths`` is named as the generator names it
(its operationId, or the method and path segments, through ``ToCamelCase``
and the prefix it gives a name that does not start with a letter) and is
read only where the generated file the directive writes, which must carry
the generator's ``Code generated by`` header, declares the operation's
builder: the request is placed at that function. Anything else (another
generator or a fork, a name normalizer other than the default, a spec or
output that is not a repository file, an operation in a ``$ref`` path item,
or an operation the output does not declare) is counted as unread.
"""

from dataclasses import dataclass
from pathlib import PurePosixPath
import re
import shlex

from .openapi import HTTP_METHODS, _operation_line, _route_line

_DIRECTIVE = re.compile(r"^//go:generate[ \t]+(.+?)\s*$", re.MULTILINE)
_PROGRAM = re.compile(
    r"github\.com/(?:oapi-codegen/oapi-codegen/v2|deepmap/oapi-codegen(?:/v2)?)"
    r"/cmd/oapi-codegen(?:@\S+)?"
)
_ACCEPTED = frozenset(
    {
        "github.com/oapi-codegen/oapi-codegen/v2",
        "github.com/deepmap/oapi-codegen",
        "github.com/deepmap/oapi-codegen/v2",
    }
)
_REQUIRED = re.compile(r"(\S+/oapi-codegen(?:-[\w-]+)?(?:/v\d+)?)\s+v\d")
_HEADER = re.compile(
    r"Code generated by github\.com/(?:oapi-codegen|deepmap)/oapi-codegen\b"
)
# Flags of the oapi-codegen command that take no value.
_BOOLEAN_FLAGS = frozenset(
    {
        "alias-types",
        "initialism-overrides",
        "old-config-style",
        "output-config",
        "version",
        "help",
        "h",
    }
)
_DEFAULT_KINDS = frozenset({"types", "client", "server", "spec"})
_SEPARATORS = frozenset("-#@!$&=.+:;_~ (){}[]")


@dataclass(frozen=True)
class GeneratedRequest:
    """The request builder oapi-codegen generates for one spec operation."""

    file: str  # the generated Go file
    line: int  # of the builder function's name
    function: str
    http_method: str  # upper case
    path: str
    spec_file: str
    spec_line: int


@dataclass(frozen=True)
class GeneratorUnread:
    file: str
    line: int
    reason: str


def camel_case(name):
    """oapi-codegen's ToCamelCase: letters and digits kept, a lower-case
    letter at the start or after a separator in upper case."""
    found, capital = [], True
    for character in name.strip(" "):
        if character.isupper() or character.isdigit():
            found.append(character)
        elif character.islower():
            found.append(character.upper() if capital else character)
        capital = character in _SEPARATORS
    return "".join(found)


def operation_name(operation_id, http_method, route):
    """The Go name oapi-codegen gives an operation: its operationId, or the
    method and path segments joined by ``-``, through ToCamelCase, with
    ``N`` in front of a name that starts with a digit and ``Empty`` for an
    empty one (typeNamePrefix of the normalized name)."""
    if not operation_id:
        operation_id = "-".join(
            [http_method.lower(), *(p for p in route.split("/") if p)]
        )
    name = camel_case(operation_id)
    if not name:
        return "Empty"
    return "N" + name if name[0].isdigit() else name


def _arguments(tokens):
    """({flag: value}, spec) of an oapi-codegen argument list, read as Go's
    flag package does: flags up to the first other argument."""
    flags, index = {}, 0
    while index < len(tokens):
        token = tokens[index]
        if token == "--":
            index += 1
            break
        if not token.startswith("-") or token == "-":
            break
        name, equals, value = token.lstrip("-").partition("=")
        if not equals:
            if name in _BOOLEAN_FLAGS:
                value = "true"
            elif index + 1 < len(tokens):
                index += 1
                value = tokens[index]
            else:
                value = None
        flags[name] = value
        index += 1
    return flags, tokens[index] if index < len(tokens) else None


def _module_file(root, directory, modfile):
    if modfile:
        path = directory / modfile
        return path if (root / path).is_file() else None
    for folder in (directory, *directory.parents):
        if (root / folder / "go.mod").is_file():
            return folder / "go.mod"
    return None


def _program(tokens, root, directory):
    """(arguments after the program, None) when the command runs
    oapi-codegen, (None, reason) when it may run another generator, (None,
    None) when it runs no oapi-codegen at all."""
    modfile = None
    if tokens[:2] in (["go", "run"], ["go", "tool"]):
        index = 2
        while index < len(tokens) and tokens[index].startswith("-"):
            flag = tokens[index]
            if flag.startswith("-modfile="):
                modfile = flag.partition("=")[2]
            elif flag == "-modfile" and index + 1 < len(tokens):
                index += 1
                modfile = tokens[index]
            index += 1
        if index >= len(tokens):
            return None, None
        program, rest = tokens[index], tokens[index + 1 :]
    else:
        program, rest = tokens[0], tokens[1:]
    if _PROGRAM.fullmatch(program):
        return rest, None
    if program != "oapi-codegen":
        if "oapi-codegen" in program:
            return None, "generator"
        return None, None
    if tokens[:2] == ["go", "tool"]:
        # go tool runs the tool its go.mod declares.
        module = _module_file(root, directory, modfile)
        manifests = [root / module] if module else []
    else:
        # A program on PATH: the generators the repository's go.mod files pin.
        manifests = [
            p
            for p in sorted(root.rglob("go.mod"))
            if not any(
                part in ("vendor", "node_modules") or part.startswith(".")
                for part in p.relative_to(root).parts
            )
        ]
    generators = set()
    for manifest in manifests:
        try:
            text = manifest.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        generators.update(m.group(1) for m in _REQUIRED.finditer(text))
    if not generators or not generators <= _ACCEPTED:
        return None, "generator"
    return rest, None


def _kinds(value):
    if isinstance(value, str):
        return {k.strip() for k in value.split(",") if k.strip()}
    if isinstance(value, list):
        return {k for k in value if isinstance(k, str)}
    if isinstance(value, dict):
        return {k for k, v in value.items() if v is True}
    return None


def _load(path, yaml):
    try:
        text = path.read_text(encoding="utf-8")
        return yaml.safe_load(text), text
    except (OSError, UnicodeDecodeError, yaml.YAMLError):
        return None, None


def _inside(root, path):
    try:
        (root / path).resolve().relative_to(root.resolve())
    except ValueError:
        return False
    return (root / path).is_file()


def _normalize(path):
    parts = []
    for part in PurePosixPath(path).parts:
        if part == "..":
            if not parts:
                return None
            parts.pop()
        elif part != ".":
            parts.append(part)
    return "/".join(parts)


def _execution(root, file, line, tokens, yaml, requests, unread):
    directory = PurePosixPath(file).parent
    arguments, reason = _program(tokens, root, directory)
    if reason:
        unread.append(GeneratorUnread(file, line, reason))
    if arguments is None:
        return
    flags, spec = _arguments(arguments)
    if "output-config" in flags or "version" in flags:
        return
    settings = {}
    if flags.get("config"):
        config = _normalize(directory / flags["config"])
        if config is None or not _inside(root, config):
            unread.append(GeneratorUnread(file, line, "config_file"))
            return
        settings, _ = _load(root / config, yaml)
        if not isinstance(settings, dict):
            unread.append(GeneratorUnread(file, line, "config_file"))
            return
    kinds = _kinds(flags["generate"]) if "generate" in flags else None
    if kinds is None and "generate" in settings:
        kinds = _kinds(settings["generate"])
    if kinds is None:
        kinds = _DEFAULT_KINDS
    if "client" not in kinds:
        return
    options = settings.get("output-options")
    if isinstance(options, dict) and options.get("name-normalizer") not in (
        None,
        "",
        "ToCamelCase",
    ):
        unread.append(GeneratorUnread(file, line, "name_normalizer"))
        return
    output = flags.get("o") or settings.get("output")
    output = _normalize(directory / output) if isinstance(output, str) else None
    if spec is None or "$" in spec or "://" in spec:
        unread.append(GeneratorUnread(file, line, "spec_file"))
        return
    spec_file = _normalize(directory / spec)
    if spec_file is None or not _inside(root, spec_file):
        unread.append(GeneratorUnread(file, line, "spec_file"))
        return
    if output is None or "$" in output or not _inside(root, output):
        unread.append(GeneratorUnread(file, line, "output_file"))
        return
    try:
        generated = (root / output).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        generated = ""
    if not _HEADER.search(generated[:2000]):
        unread.append(GeneratorUnread(file, line, "output_file"))
        return
    document, text = _load(root / spec_file, yaml)
    paths = document.get("paths") if isinstance(document, dict) else None
    if not isinstance(paths, dict) or "swagger" in document:
        unread.append(GeneratorUnread(file, line, "spec_file"))
        return
    builders = {
        m.group(1): generated.count("\n", 0, m.start(1)) + 1
        for m in re.finditer(r"^func (New\w+)\(", generated, re.MULTILINE)
    }
    for route, item in paths.items():
        if not isinstance(item, dict) or not isinstance(route, str):
            continue
        if "$ref" in item:
            unread.append(GeneratorUnread(spec_file, _route_line(text, route), "ref"))
            continue
        for http_method in HTTP_METHODS:
            operation = item.get(http_method)
            if not isinstance(operation, dict):
                continue
            operation_id = operation.get("operationId")
            if not isinstance(operation_id, str) or not operation_id:
                operation_id = None
            spec_line = (
                _operation_line(text, operation_id)
                if operation_id
                else _route_line(text, route)
            )
            name = operation_name(operation_id, http_method, route)
            function = next(
                (
                    f
                    for f in (f"New{name}RequestWithBody", f"New{name}Request")
                    if f in builders
                ),
                None,
            )
            if function is None:
                unread.append(GeneratorUnread(spec_file, spec_line, "not_generated"))
                continue
            requests.append(
                GeneratedRequest(
                    output,
                    builders[function],
                    function,
                    http_method.upper(),
                    route,
                    spec_file,
                    spec_line,
                )
            )


def generated_requests(root, go_files):
    """([GeneratedRequest], [GeneratorUnread]) of the oapi-codegen
    directives in ``go_files`` ({path: content bytes}, paths relative to
    ``root``)."""
    try:
        import yaml
    except ImportError:  # pyyaml comes with the languages extra
        return [], []
    requests, unread = [], []
    for file, content in sorted(go_files.items()):
        if b"go:generate" not in content or b"oapi-codegen" not in content:
            continue
        source = content.decode("utf-8", errors="replace")
        for match in _DIRECTIVE.finditer(source):
            if "oapi-codegen" not in match.group(1):
                continue
            line = source.count("\n", 0, match.start()) + 1
            try:
                tokens = shlex.split(match.group(1))
            except ValueError:
                unread.append(GeneratorUnread(file, line, "command"))
                continue
            if tokens:
                _execution(root, file, line, tokens, yaml, requests, unread)
    return list(dict.fromkeys(requests)), unread
