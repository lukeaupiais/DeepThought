def _write(root, files):
    for path, text in files.items():
        target = Path(root) / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")


def _read(root):
    files = {
        p.relative_to(root).as_posix(): p.read_bytes() for p in Path(root).rglob("*.go")
    }
    return generated_requests(Path(root), files)


class NamingTests(unittest.TestCase):
    def test_camel_case(self):
        # oapi-codegen's ToCamelCase: separators drop and capitalize the next
        # lower-case letter; other letters and digits are kept as written.
        self.assertEqual(camel_case("list-tasks"), "ListTasks")
        self.assertEqual(camel_case("getV1License"), "GetV1License")
        self.assertEqual(camel_case("get_v1.license status"), "GetV1LicenseStatus")
        self.assertEqual(camel_case("v1beta"), "V1beta")

    def test_operation_name(self):
        self.assertEqual(operation_name("createTask", "post", "/tasks"), "CreateTask")
        self.assertEqual(operation_name(None, "get", "/tasks/{id}"), "GetTasksId")
        self.assertEqual(operation_name("2fa-check", "get", "/x"), "N2faCheck")


@unittest.skipUnless(YAML, "pyyaml is not installed")
class DirectiveTests(unittest.TestCase):
    def test_flags(self):
        with tempfile.TemporaryDirectory() as root:
            _write(
                root,
                {
                    "go.mod": GO_MOD,
                    "api/tasks.yaml": SPEC,
                    "client/generate.go": (
                        "package client\n\n//go:generate go run "
                        f"{PROGRAM}@v2.4.1 -generate types,client -package "
                        "client -o client.gen.go ../api/tasks.yaml\n"
                    ),
                    "client/client.gen.go": CLIENT,
                },
            )
            requests, unread = _read(root)
        self.assertEqual(
            sorted(
                (r.file, r.function, r.http_method, r.path, r.spec_file, r.spec_line)
                for r in requests
            ),
            [
                (
                    "client/client.gen.go",
                    "NewCreateTaskRequestWithBody",
                    "POST",
                    "/tasks",
                    "api/tasks.yaml",
                    8,
                ),
                (
                    "client/client.gen.go",
                    "NewGetTasksIdRequest",
                    "GET",
                    "/tasks/{id}",
                    "api/tasks.yaml",
                    9,
                ),
                (
                    "client/client.gen.go",
                    "NewListTasksRequest",
                    "GET",
                    "/tasks",
                    "api/tasks.yaml",
                    6,
                ),
            ],
        )
        self.assertEqual(
            [(u.file, u.line, u.reason) for u in unread],
            [("api/tasks.yaml", 13, "not_generated")],
        )

    def test_config_file(self):
        with tempfile.TemporaryDirectory() as root:
            _write(
                root,
                {
                    # go tool runs the tool its go.mod declares.
                    "go.mod": GO_MOD + f"\ntool {PROGRAM}\n",
                    "api/tasks.yaml": SPEC,
                    "client/generate.go": (
                        "package client\n\n"
                        "//go:generate go tool oapi-codegen --config=client.cfg.yaml "
                        "../api/tasks.yaml\n"
                        "//go:generate go tool oapi-codegen -config server.cfg.yaml "
                        "../api/tasks.yaml\n"
                    ),
                    "client/client.cfg.yaml": (
                        "package: client\ngenerate:\n  client: true\n"
                        "output: gen/client.gen.go\n"
                    ),
                    # Generates no client.
                    "client/server.cfg.yaml": (
                        "package: client\ngenerate:\n  chi-server: true\n"
                        "output: gen/server.gen.go\n"
                    ),
                    "client/gen/client.gen.go": CLIENT,
                },
            )
            requests, unread = _read(root)
        self.assertEqual(
            sorted((r.file, r.function) for r in requests),
            [
                ("client/gen/client.gen.go", "NewCreateTaskRequestWithBody"),
                ("client/gen/client.gen.go", "NewGetTasksIdRequest"),
                ("client/gen/client.gen.go", "NewListTasksRequest"),
            ],
        )
        self.assertEqual([u.reason for u in unread], ["not_generated"])

    def test_unread(self):
        files = {
            "api/tasks.yaml": SPEC,
            "client/client.gen.go": CLIENT,
            "client/normalized.cfg.yaml": (
                "package: client\ngenerate: {client: true}\n"
                "output: client.gen.go\n"
                "output-options: {name-normalizer: ToCamelCaseWithInitialisms}\n"
            ),
            "client/generate.go": (
                "package client\n\n"
                # A fork of the generator, which may name things differently.
                "//go:generate go run github.com/doordash-oss/oapi-codegen-dd/v3"
                "/cmd/oapi-codegen -generate client -o client.gen.go "
                "../api/tasks.yaml\n"
                "//go:generate go run "
                f"{PROGRAM} -config normalized.cfg.yaml ../api/tasks.yaml\n"
                # Written to standard output, and a spec outside the repository.
                f"//go:generate go run {PROGRAM} -generate client ../api/tasks.yaml\n"
                f"//go:generate go run {PROGRAM} -generate client -o client.gen.go "
                "https://example.com/tasks.yaml\n"
                # A bare program name the repository's go.mod does not pin.
                "//go:generate oapi-codegen -generate client -o client.gen.go "
                "../api/tasks.yaml\n"
            ),
            "go.mod": "module example.com/tasks\n\ngo 1.24\n",
        }
        with tempfile.TemporaryDirectory() as root:
            _write(root, files)
            requests, unread = _read(root)
        self.assertEqual(requests, [])
        self.assertEqual(
            [(u.line, u.reason) for u in unread],
            [
                (3, "generator"),
                (4, "name_normalizer"),
                (5, "output_file"),
                (6, "spec_file"),
                (7, "generator"),
            ],
        )


@unittest.skipUnless(READY, "the Go grammar or pyyaml is not installed")
class ToolTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.directory = tempfile.TemporaryDirectory()
        _write(
            cls.directory.name,
            {
                **go_stub_files(),
                "go.mod": SERVER_GO_MOD,
                "api/tasks.yaml": SPEC,
                "client/generate.go": (
                    f"package client\n\n//go:generate go run {PROGRAM} -generate "
                    "client -o client.gen.go ../api/tasks.yaml\n"
                ),
                "client/client.gen.go": CLIENT,
                # The client is another module: a request with an unknown
                # base is not matched to routes of its own project.
                "client/go.mod": "module example.com/tasks/client\n\ngo 1.24\n",
                "server/main.go": SERVER,
            },
        )
        cls.tool = ServiceContractTool(Path(cls.directory.name))
        cls.output = asyncio.run(cls.tool.analyze("repo"))

    @classmethod
    def tearDownClass(cls):
        cls.directory.cleanup()

    def test_requests(self):
        _, routes, requests, _, resolutions = self.tool.last_facts
        # The builders' own http.NewRequest calls, whose URLs are unknown,
        # give way to the spec's operations.
        self.assertEqual(
            sorted(
                (r.line, r.client, r.method, r.url, r.declared_in) for r in requests
            ),
            [
                (12, "oapi-codegen", "GET", "\x00/tasks", "api/tasks.yaml:6"),
                (32, "oapi-codegen", "POST", "\x00/tasks", "api/tasks.yaml:8"),
                (49, "oapi-codegen", "GET", "\x00/tasks/{id}", "api/tasks.yaml:9"),
            ],
        )
        by_id = {r.id: r for r in routes}
        self.assertEqual(
            sorted(
                (res.status, res.rule_id, by_id[res.route_id].methods)
                for res in resolutions
            ),
            [
                ("linked", "service-contracts.http-path", ("GET",)),
                ("linked", "service-contracts.http-path", ("GET",)),
                ("linked", "service-contracts.http-path", ("POST",)),
            ],
        )

    def test_graph(self):
        found = sorted(
            (
                r.properties["line"],
                r.properties["rule_id"],
                r.properties["declared_in"],
                r.source_match["qualified_name"].split("::")[2],
            )
            for r in self.output.relationships
            if r.type == "REQUESTS"
        )
        self.assertEqual(
            found[0],
            (
                12,
                "service-contracts.oapi-codegen-client-path",
                "api/tasks.yaml:6",
                "NewListTasksRequest",
            ),
        )
        rule = get_rule("service-contracts.oapi-codegen-client-path")
        self.assertEqual(rule.evidence_type, "pattern_matched")
        self.assertEqual(
            self.output.metadata.custom_metrics["unread"].get(
                "oapi_codegen:not_generated"
            ),
            1,
        )


if __name__ == "__main__":
    unittest.main()
