"""Requests in TypeScript clients @hey-api/openapi-ts generated from an
OpenAPI spec: each operation calls the client method named for its HTTP
method with {url, ...}, or __request(OpenAPI, {method, url}) in legacy
clients."""

import asyncio
import importlib.util
from pathlib import Path
import tempfile
import unittest

from deepthought.analysis_tools import ServiceContractTool
from deepthought.service_contracts.http import PLACEHOLDER
from typescript_ready import needs_typescript

READY = importlib.util.find_spec("tree_sitter") and importlib.util.find_spec(
    "tree_sitter_typescript"
)

HEADER = "// This file is auto-generated by @hey-api/openapi-ts\n\n"

FILES = {
    "web/src/client/sdk.gen.ts": HEADER
    + (
        "import { client } from './client.gen';\n"
        "export class ItemsService {\n"
        "  public static readItems(options?: Options) {\n"
        "    return (options?.client ?? client).get({\n"
        "      responseType: 'json',\n"
        "      url: '/api/v1/items/',\n"
        "      ...options,\n"
        "    });\n"
        "  }\n"
        "  public static deleteItem(options: Options) {\n"
        "    return (options.client ?? client).delete({\n"
        "      url: '/api/v1/items/{id}',\n"
        "      ...options,\n"
        "    });\n"
        "  }\n"
        "}\n"
        # Not a request config: no url.
        "export const setup = () => client.get({ responseType: 'json' });\n"
    ),
    "web/src/legacy/services.gen.ts": HEADER
    + (
        "import { OpenAPI } from './core/OpenAPI';\n"
        "import { request as __request } from './core/request';\n"
        "export const readUser = (data: Data) =>\n"
        "  __request(OpenAPI, {\n"
        "    method: 'GET',\n"
        "    url: '/api/v1/users/{user_id}',\n"
        "    path: { user_id: data.userId },\n"
        "  });\n"
    ),
    # The same call shape in a file it did not generate is not read.
    "web/src/handwritten.ts": (
        "import { client } from './client/client.gen';\n"
        "export const other = () => client.get({ url: '/other' });\n"
    ),
    "server/src/app.ts": (
        "import express from 'express';\n"
        "const app = express();\n"
        "app.delete('/api/v1/items/:id', (req, res) => res.json({}));\n"
    ),
}


@unittest.skipUnless(READY, "tree-sitter grammars are not installed")
@needs_typescript
class HeyApiTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        root = Path(self.directory.name)
        for name, text in FILES.items():
            path = root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        self.tool = ServiceContractTool(root)
        self.output = asyncio.run(self.tool.analyze("r"))

    def tearDown(self):
        self.directory.cleanup()

    def test_requests(self):
        _, _, requests, _, _ = self.tool.last_facts
        found = sorted(
            (q.file, q.line, q.client, q.method, q.url.replace(PLACEHOLDER, "{?}"))
            for q in requests
        )
        self.assertEqual(
            found,
            [
                ("web/src/client/sdk.gen.ts", 6, "hey-api", "GET", "/api/v1/items/"),
                (
                    "web/src/client/sdk.gen.ts",
                    13,
                    "hey-api",
                    "DELETE",
                    "/api/v1/items/{?}",
                ),
                (
                    "web/src/legacy/services.gen.ts",
                    6,
                    "hey-api",
                    "GET",
                    "/api/v1/users/{?}",
                ),
            ],
        )

    def test_links_carry_the_hey_api_rule(self):
        linked = sorted(
            (r.properties["request"], r.properties["rule_id"])
            for r in self.output.relationships
            if r.type == "REQUESTS"
        )
        self.assertEqual(
            linked,
            [("DELETE /api/v1/items/{?}", "service-contracts.hey-api-client-path")],
        )


if __name__ == "__main__":
    unittest.main()
