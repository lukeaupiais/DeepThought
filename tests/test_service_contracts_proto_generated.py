"""Go types protoc-gen-go generates, linked to the protobuf types they are
generated from (GENERATED_FROM)."""

import asyncio
from pathlib import Path
import tempfile
import unittest

from deepthought.analysis_tools import ServiceContractTool
from deepthought.service_contracts.protoc import (
    available,
    declared_types,
    flattened_types,
    python_descriptors,
)
from go_stubs import go_mod, go_stub_files, needs_go
from typescript_ready import needs_typescript

PROTO = """syntax = "proto3";
package shop.v1;
option go_package = "example.com/shop/pb";

enum Channel {
  CHANNEL_UNSPECIFIED = 0;
}

message Order {
  message Line {
    enum Kind {
      KIND_UNSPECIFIED = 0;
    }
    string sku = 1;
    Kind kind = 2;
  }
  enum Status {
    STATUS_UNSPECIFIED = 0;
  }
  repeated Line lines = 1;
  map<string, int32> totals = 2;
  Status status = 3;
  Channel channel = 4;
}

message Item {
  message Tag { string name = 1; }
  repeated Tag tags = 1;
}
"""

# protoc-gen-go 1.36's GoTypes for PROTO: enums, then messages, in
# protobuf-go's flattened ordering; the map entry has no Go type.
GO_TYPES = """\t(Channel)(0),         // 0: shop.v1.Channel
\t(Order_Status)(0),    // 1: shop.v1.Order.Status
\t(Order_Line_Kind)(0), // 2: shop.v1.Order.Line.Kind
\t(*Order)(nil),        // 3: shop.v1.Order
\t(*Item)(nil),         // 4: shop.v1.Item
\t(*Order_Line)(nil),   // 5: shop.v1.Order.Line
\tnil,                  // 6: shop.v1.Order.TotalsEntry
\t(*Item_Tag)(nil),     // 7: shop.v1.Item.Tag
"""

ORDER = [
    "shop.v1.Channel",
    "shop.v1.Order.Status",
    "shop.v1.Order.Line.Kind",
    "shop.v1.Order",
    "shop.v1.Item",
    "shop.v1.Order.Line",
    "shop.v1.Order.TotalsEntry",
    "shop.v1.Item.Tag",
]


def _descriptor():
    """PROTO's FileDescriptorProto, serialized, as protoc compiles it."""
    from grpc_tools import protoc

    with tempfile.TemporaryDirectory() as directory:
        (Path(directory) / "order.proto").write_text(PROTO, encoding="utf-8")
        out = Path(directory) / "set.pb"
        code = protoc.main(
            ["protoc", f"-I{directory}", f"--descriptor_set_out={out}", "order.proto"]
        )
        assert code == 0
        from google.protobuf import descriptor_pb2

        files = descriptor_pb2.FileDescriptorSet.FromString(out.read_bytes())
    return files.file[0].SerializeToString()


def _go_string(data):
    return '"' + "".join(f"\\x{b:02x}" for b in data) + '"'


def _generated(data, form):
    """A cut-down protoc-gen-go file for PROTO. ``form`` is how its
    RawDescriptor is written: "string" (protoc-gen-go 1.36: a string
    constant through unsafe.Slice) or "bytes" (earlier: a []byte literal)."""
    if form == "string":
        raw = f"const file_order_proto_rawDesc = {_go_string(data)}\n"
        descriptor = (
            "unsafe.Slice(unsafe.StringData(file_order_proto_rawDesc), "
            "len(file_order_proto_rawDesc))"
        )
        imports = '\t"unsafe"\n'
    else:
        raw = (
            "var file_order_proto_rawDesc = []byte{\n"
            + "".join(f"\t0x{b:02x},\n" for b in data)
            + "}\n"
        )
        descriptor = "file_order_proto_rawDesc"
        imports = ""
    types = "".join(
        f"type {name} {kind}\n\nfunc ({receiver}) ProtoReflect() int {{ return 0 }}\n\n"
        for name, kind, receiver in (
            ("Channel", "int32", "Channel"),
            ("Order_Status", "int32", "Order_Status"),
            ("Order_Line_Kind", "int32", "Order_Line_Kind"),
            ("Order", "struct{ Lines []*Order_Line }", "*Order"),
            ("Item", "struct{ Tags []*Item_Tag }", "*Item"),
            ("Order_Line", "struct{ Sku string }", "*Order_Line"),
            ("Item_Tag", "struct{ Name string }", "*Item_Tag"),
        )
    )
    return (
        "// Code generated by protoc-gen-go. DO NOT EDIT.\n"
        "// source: order.proto\n\n"
        "package pb\n\n"
        "import (\n"
        '\tprotoimpl "google.golang.org/protobuf/runtime/protoimpl"\n'
        f"{imports})\n\n"
        f"{types}"
        f"{raw}\n"
        f"var file_order_proto_goTypes = []any{{\n{GO_TYPES}}}\n\n"
        "func init() {\n"
        "\t_ = protoimpl.TypeBuilder{\n"
        "\t\tFile: protoimpl.DescBuilder{\n"
        f"\t\t\tRawDescriptor: {descriptor},\n"
        "\t\t\tNumEnums:      3,\n"
        "\t\t\tNumMessages:   5,\n"
        "\t\t},\n"
        "\t\tGoTypes: file_order_proto_goTypes,\n"
        "\t}.Build()\n"
        "}\n"
    )


@unittest.skipUnless(available(), "grpcio-tools is not installed")
class FlattenedOrderTests(unittest.TestCase):
    def test_protobuf_go_flattened_ordering(self):
        self.assertEqual(flattened_types(_descriptor(), 3, 5), ORDER)

    def test_counts_must_match(self):
        self.assertIsNone(flattened_types(_descriptor(), 3, 4))
        self.assertIsNone(flattened_types(b"\xff\xff", 0, 0))


@unittest.skipUnless(available(), "grpcio-tools is not installed")
@needs_go
@needs_typescript
class GoGeneratedTypeTests(unittest.TestCase):
    def generated_from(self, form, proto=True):
        files = {
            **go_stub_files(),
            "svc/go.mod": go_mod("example.com/shop", "google.golang.org/protobuf"),
            "svc/pb/order.pb.go": _generated(_descriptor(), form),
        }
        if proto:
            files["proto/order.proto"] = PROTO
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for path, text in files.items():
                target = root / path
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
            output = asyncio.run(ServiceContractTool(root).analyze("r"))
        edges = [r for r in output.relationships if r.type == "GENERATED_FROM"]
        for edge in edges:
            self.assertEqual(edge.properties["evidence_type"], "resolved")
        return sorted(
            (
                r.source_match["qualified_name"].split("::")[2],
                r.target_match["qualified_name"].removeprefix("r::proto::"),
                r.properties["line"],
            )
            for r in edges
        ), output.metadata.custom_metrics

    def test_each_type_links_to_its_declaration(self):
        for form in ("string", "bytes"):
            with self.subTest(form=form):
                found, metrics = self.generated_from(form)
                self.assertEqual(
                    [(name, target) for name, target, _ in found],
                    [
                        ("Channel", "enum::shop.v1.Channel"),
                        ("Item", "message::shop.v1.Item"),
                        ("Item_Tag", "message::shop.v1.Item.Tag"),
                        ("Order", "message::shop.v1.Order"),
                        ("Order_Line", "message::shop.v1.Order.Line"),
                        ("Order_Line_Kind", "enum::shop.v1.Order.Line.Kind"),
                        ("Order_Status", "enum::shop.v1.Order.Status"),
                    ],
                )
                self.assertEqual(metrics["proto_generated_types"], 7)

    def test_no_proto_in_the_repository_links_nothing(self):
        found, _ = self.generated_from("string", proto=False)
        self.assertEqual(found, [])


def _pb2(data, form):
    """A protoc Python module for PROTO: the builder form protoc writes
    since protobuf 3.20, or the older FileDescriptor form."""
    if form == "builder":
        return (
            "from google.protobuf.internal import builder as _builder\n"
            "from google.protobuf import descriptor_pool as _descriptor_pool\n"
            "DESCRIPTOR = _descriptor_pool.Default().AddSerializedFile("
            f"{data!r})\n"
            "_builder.BuildMessageAndEnumDescriptors(DESCRIPTOR, globals())\n"
        )
    return (
        "from google.protobuf import descriptor as _descriptor\n"
        "DESCRIPTOR = _descriptor.FileDescriptor(\n"
        "  name='order.proto', package='shop.v1', syntax='proto3',\n"
        f"  serialized_pb={data!r})\n"
    )


@unittest.skipUnless(available(), "grpcio-tools is not installed")
class PythonGeneratedModuleTests(unittest.TestCase):
    def test_descriptor_literals(self):
        data = _descriptor()
        for form in ("builder", "descriptor"):
            with self.subTest(form=form):
                self.assertEqual(python_descriptors(_pb2(data, form)), [data])
        # Not protobuf's descriptor pool: nothing is read.
        self.assertEqual(
            python_descriptors(f"pool = Pool()\npool.AddSerializedFile({data!r})\n"),
            [],
        )
        self.assertIn(("message", "shop.v1.Order.TotalsEntry"), declared_types(data))

    @needs_typescript
    def test_module_links_to_its_types(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            files = {
                "proto/order.proto": PROTO,
                "svc/order_pb2.py": _pb2(_descriptor(), "builder"),
            }
            for path, text in files.items():
                target = root / path
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
            output = asyncio.run(ServiceContractTool(root).analyze("r"))
        found = sorted(
            (
                r.source_match["qualified_name"],
                r.target_match["qualified_name"].removeprefix("r::proto::"),
                r.properties["rule_id"],
            )
            for r in output.relationships
            if r.type == "GENERATED_FROM"
        )
        rule = "service-contracts.python-generated-proto-module"
        self.assertEqual(
            found,
            [
                ("r::svc/order_pb2.py::file", f"{kind}::shop.v1.{name}", rule)
                for kind, name in (
                    ("enum", "Channel"),
                    ("enum", "Order.Line.Kind"),
                    ("enum", "Order.Status"),
                    ("message", "Item"),
                    ("message", "Item.Tag"),
                    ("message", "Order"),
                    ("message", "Order.Line"),
                )
            ],
        )


if __name__ == "__main__":
    unittest.main()
